// Turn the measured readings into results/results.json (for pages) and results/results.md (to read).
//
//   node scripts/report.mjs
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const ROOT = new URL("..", import.meta.url).pathname
const read = (path) => JSON.parse(readFileSync(join(ROOT, path), "utf8"))
const data = read("phrases.json")
const release = read("results/chrono-2.10.3.json")
const fixed = read("results/chrono-fixes.json")
const perFixDir = join(ROOT, "results", "per-fix")
const perFix = existsSync(perFixDir)
  ? readdirSync(perFixDir).filter((f) => f.endsWith(".json")).sort().map((f) => ({ branch: f.replace(/\.json$/, ""), ...read(`results/per-fix/${f}`) }))
  : []

const OUTCOMES = ["right", "wrong date", "wrong time", "missed"]
const byId = (run) => new Map(run.readings.map((r) => [r.id, r]))
const releaseById = byId(release)
const fixedById = byId(fixed)

const count = (run) => Object.fromEntries(OUTCOMES.map((o) => [o, run.readings.filter((r) => r.outcome === o).length]))
const groups = [...new Set(data.phrases.map((p) => p.group))]
const groupRows = groups.map((g) => {
  const ids = data.phrases.filter((p) => p.group === g).map((p) => p.id)
  const right = (m) => ids.filter((id) => m.get(id)?.outcome === "right").length
  return { group: g, phrases: ids.length, release: right(releaseById), fixed: right(fixedById) }
})
const fixRows = perFix.map((f) => {
  const fixes = f.readings.filter((r) => r.outcome === "right" && releaseById.get(r.id)?.outcome !== "right").map((r) => r.id)
  const breaks = f.readings.filter((r) => r.outcome !== "right" && releaseById.get(r.id)?.outcome === "right").map((r) => r.id)
  return { branch: f.branch, fixes, breaks }
})

const show = (r) => (r?.read ? `${r.read.date} ${r.read.time}` : "nothing")
const expected = (p) => {
  const date = typeof p.date === "string" ? p.date : Array.isArray(p.date) ? p.date.join(" or ") : `${p.date.from} to ${p.date.to}`
  const time = p.time === null || p.time === undefined ? "" : typeof p.time === "string" ? ` ${p.time}` : ` ${p.time.from}–${p.time.to}`
  return date + time
}

const summary = { release: { parser: release.parser, ...count(release) }, fixed: { parser: fixed.parser, ...count(fixed) } }
const phrases = data.phrases.map((p) => ({ ...p, release: releaseById.get(p.id), fixed: fixedById.get(p.id) }))
writeFileSync(join(ROOT, "results", "results.json"), JSON.stringify({ reference: data.reference, summary, groups: groupRows, fixes: fixRows, phrases }, null, 2) + "\n")

const lines = [
  "# Results",
  "",
  `Generated by \`node scripts/report.mjs\`. Reference moment: ${data.reference} (Wednesday, Jakarta). chrono's casual`,
  "Indonesian parser, with `forwardDate: true`.",
  "",
  "| Parser | Right | Wrong date | Wrong time | Missed |",
  "|---|---:|---:|---:|---:|",
  ...[summary.release, summary.fixed].map((s) => `| ${s.parser} | ${s.right} | ${s["wrong date"]} | ${s["wrong time"]} | ${s.missed} |`),
  "",
  "## By kind of phrase",
  "",
  "| Kind | Phrases | Right in the release | Right with the fixes |",
  "|---|---:|---:|---:|",
  ...groupRows.map((g) => `| ${g.group} | ${g.phrases} | ${g.release} | ${g.fixed} |`),
  "",
]
if (fixRows.length) {
  lines.push("## Each fix on its own", "", "| Branch | Phrases it fixes | Phrases it breaks |", "|---|---:|---:|")
  for (const f of fixRows) lines.push(`| ${f.branch} | ${f.fixes.length} | ${f.breaks.length} |`)
  lines.push("")
}
lines.push("## Every phrase", "", "| # | Phrase | Means | Release read | With the fixes |", "|---|---|---|---|---|")
for (const p of phrases) {
  const mark = (r) => `${show(r)}${r?.outcome === "right" ? "" : ` (${r?.outcome})`}`
  lines.push(`| ${p.id} | ${p.text.replace(/\|/g, "\\|")} | ${expected(p)} | ${mark(p.release)} | ${mark(p.fixed)} |`)
}
writeFileSync(join(ROOT, "results", "results.md"), lines.join("\n") + "\n")
process.stdout.write(`${phrases.length} phrases -> results/results.json, results/results.md\n`)
